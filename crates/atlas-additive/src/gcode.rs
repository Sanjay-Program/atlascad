//! Multi-dialect G-code emitter for 3D printers.

use crate::settings::{PrinterDialect, SlicerSettings};

/// Emitter for ISO / RepRap 3D printer G-code.
pub struct GCodeEmitter<'a> {
    settings: &'a SlicerSettings,
    buffer: String,
    current_e: f64,
    current_f: f64,
}

impl<'a> GCodeEmitter<'a> {
    pub fn new(settings: &'a SlicerSettings) -> Self {
        Self {
            settings,
            buffer: String::with_capacity(16 * 1024),
            current_e: 0.0,
            current_f: 0.0,
        }
    }

    /// Emit standard printer initialization sequence.
    pub fn emit_header(&mut self) {
        let dialect_name = match self.settings.dialect {
            PrinterDialect::Marlin => "Marlin / RepRap",
            PrinterDialect::Klipper => "Klipper",
            PrinterDialect::RepRap => "RepRapFirmware",
            PrinterDialect::Prusa => "Prusa-Marlin",
        };

        self.buffer
            .push_str("; ================================================\n");
        self.buffer
            .push_str("; Generated by AtlasCAD Additive Slicer v0.1.0\n");
        self.buffer
            .push_str(&format!("; Target Firmware: {}\n", dialect_name));
        self.buffer
            .push_str(&format!("; Material: {}\n", self.settings.material.name));
        self.buffer.push_str(&format!(
            "; Layer Height: {:.2} mm\n",
            self.settings.layer_height_mm
        ));
        self.buffer.push_str(&format!(
            "; Line Width: {:.2} mm\n",
            self.settings.line_width_mm
        ));
        self.buffer
            .push_str("; ================================================\n\n");

        // Units and coordinate mode
        self.buffer.push_str("G21 ; Set units to millimeters\n");
        self.buffer.push_str("G90 ; Absolute coordinates\n");
        self.buffer
            .push_str("M82 ; Absolute extruder positioning\n");

        // Bed temperature
        self.buffer.push_str(&format!(
            "M140 S{:.0} ; Set bed temperature\n",
            self.settings.bed_temp_c
        ));
        self.buffer.push_str(&format!(
            "M190 S{:.0} ; Wait for bed temperature\n",
            self.settings.bed_temp_c
        ));

        // Nozzle temperature
        self.buffer.push_str(&format!(
            "M104 S{:.0} ; Set extruder temperature\n",
            self.settings.nozzle_temp_c
        ));
        self.buffer.push_str(&format!(
            "M109 S{:.0} ; Wait for extruder temperature\n",
            self.settings.nozzle_temp_c
        ));

        // Homing and prime line
        self.buffer.push_str("G28 ; Home all axes\n");
        self.buffer.push_str("G92 E0 ; Reset extruder\n");
        self.buffer.push_str("G1 Z2.0 F3000 ; Move Z Axis up\n");
        self.buffer
            .push_str("G1 X0.1 Y20 Z0.28 F5000.0 ; Move to start position\n");
        self.buffer
            .push_str("G1 X0.1 Y120.0 Z0.28 F1500.0 E9.0 ; Draw the first prime line\n");
        self.buffer
            .push_str("G1 X0.4 Y120.0 Z0.28 F5000.0 ; Move to side\n");
        self.buffer
            .push_str("G1 X0.4 Y20 Z0.28 F1500.0 E18.0 ; Draw the second prime line\n");
        self.buffer.push_str("G92 E0 ; Reset extruder\n");
        self.buffer.push_str("G1 Z2.0 F3000 ; Move Z Axis up\n\n");

        self.current_e = 0.0;
    }

    /// Announce the start of a new layer.
    pub fn emit_layer_start(&mut self, layer_idx: usize, z_height_mm: f64) {
        self.buffer.push_str(&format!("\n;LAYER:{}\n", layer_idx));
        self.buffer.push_str(&format!(";Z:{:.3}\n", z_height_mm));
        self.buffer
            .push_str(&format!("G1 Z{:.3} F3000\n", z_height_mm));
    }

    /// Emit rapid non-extruding travel move.
    pub fn emit_travel(&mut self, x: f64, y: f64) {
        let f = self.settings.travel_speed_mm_s * 60.0;
        self.buffer
            .push_str(&format!("G1 X{:.3} Y{:.3} F{:.0}\n", x, y, f));
        self.current_f = f;
    }

    /// Emit coordinated extrusion move.
    pub fn emit_extrusion(&mut self, x: f64, y: f64, distance_mm: f64) {
        // Calculate volumetric extrusion:
        let bead_area = self.settings.line_width_mm * self.settings.layer_height_mm;
        let vol_mm3 = bead_area * distance_mm;
        let fil_radius = self.settings.filament_diameter_mm * 0.5;
        let fil_area = std::f64::consts::PI * fil_radius * fil_radius;
        let delta_e = if fil_area > 1e-6 {
            vol_mm3 / fil_area
        } else {
            0.0
        };

        self.current_e += delta_e;
        let f = self.settings.print_speed_mm_s * 60.0;

        if (self.current_f - f).abs() > 1.0 {
            self.buffer.push_str(&format!(
                "G1 X{:.3} Y{:.3} E{:.4} F{:.0}\n",
                x, y, self.current_e, f
            ));
            self.current_f = f;
        } else {
            self.buffer
                .push_str(&format!("G1 X{:.3} Y{:.3} E{:.4}\n", x, y, self.current_e));
        }
    }

    /// Emit retraction move to relieve nozzle pressure.
    pub fn emit_retraction(&mut self) {
        self.current_e -= self.settings.retract_distance_mm;
        let f = self.settings.retract_speed_mm_s * 60.0;
        self.buffer
            .push_str(&format!("G1 E{:.4} F{:.0}\n", self.current_e, f));
    }

    /// Emit un-retraction move before continuing extrusion.
    pub fn emit_unretraction(&mut self) {
        self.current_e += self.settings.retract_distance_mm;
        let f = self.settings.retract_speed_mm_s * 60.0;
        self.buffer
            .push_str(&format!("G1 E{:.4} F{:.0}\n", self.current_e, f));
    }

    /// Emit standard printer shutdown sequence.
    pub fn emit_footer(&mut self) {
        self.buffer
            .push_str("\n; ================================================\n");
        self.buffer.push_str("; End of G-code sequence\n");
        self.buffer
            .push_str("; ================================================\n");
        self.buffer.push_str("M104 S0 ; Turn off extruder heater\n");
        self.buffer.push_str("M140 S0 ; Turn off bed heater\n");
        self.buffer.push_str("M107 ; Turn off parts cooling fan\n");
        self.buffer.push_str("G91 ; Relative positioning\n");
        self.buffer.push_str("G1 Z5 F3000 ; Raise nozzle 5mm\n");
        self.buffer.push_str("G90 ; Absolute positioning\n");
        self.buffer.push_str("G28 X0 Y0 ; Home X and Y\n");
        self.buffer.push_str("M84 ; Disable stepper motors\n");
    }

    /// Finalize and return the emitted G-code string.
    pub fn finish(mut self) -> String {
        self.emit_footer();
        self.buffer
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_gcode_emitter_workflow() {
        let settings = SlicerSettings::default();
        let mut emitter = GCodeEmitter::new(&settings);
        emitter.emit_header();
        emitter.emit_layer_start(0, 0.28);
        emitter.emit_travel(10.0, 10.0);
        emitter.emit_extrusion(20.0, 10.0, 10.0);
        emitter.emit_retraction();
        emitter.emit_travel(30.0, 30.0);
        emitter.emit_unretraction();
        emitter.emit_extrusion(40.0, 30.0, 10.0);
        let gcode = emitter.finish();

        assert!(gcode.contains("G21"));
        assert!(gcode.contains(";LAYER:0"));
        assert!(gcode.contains("M104 S0"));
    }
}
